"""KojoCode solution walkthrough: a NeetCode-style video Kojo "records" for a problem.

Four chapters, played back by the client like a video:
1. breakdown   Kojo reads the problem and breaks it down.
2. approaches  Possible solutions, their complexity, and why each works or fails.
3. drawing     Kojo sketches how the problem works, in ink on a scratch pad.
4. code        Kojo types the solution line by line, explaining each line.

Generated by two LLM calls (the script, then the sketch, which needs the chosen
approach), both through LLMService's normal fallback chain, then cached on the
LCSolutionArticle row forever. Everything the model returns is normalized here:
counts capped, coordinates clamped, malformed pieces dropped, so the client can
trust the shape.
"""
from __future__ import annotations

from typing import Any

# Sketch canvas the model draws on. The client scales it onto the ink paper.
CANVAS_W = 100
CANVAS_H = 60
INK_COLORS = ("ink", "red", "blue", "green")
VERDICTS = ("optimal", "works", "too slow", "fails")

MAX_BREAKDOWN = 5
MAX_APPROACHES = 3
MAX_FRAMES = 7
MAX_STROKES_PER_FRAME = 30
MAX_POINTS_PER_STROKE = 24
MAX_LABELS_PER_FRAME = 16
MAX_CODE_LINES = 80
SAY_CHARS = 400


def _text(value: Any, limit: int) -> str:
    return str(value or "").strip()[:limit]


def _num(value: Any, high: float) -> float | None:
    try:
        n = float(value)
    except (TypeError, ValueError):
        return None
    if n != n:  # NaN
        return None
    return round(min(max(n, 0.0), high), 1)


def script_prompt(title: str, statement: str, starter_code: str) -> str:
    return f"""You are Kojo, a coding-interview coach recording a NeetCode-style video walkthrough of a problem.

PROBLEM TITLE: {(title or "this problem").strip()[:300]}

PROBLEM STATEMENT:
{(statement or "(no statement provided)").strip()[:12000]}

STARTER CODE (match this Solution class, method name and parameters exactly):
```python
{(starter_code or "# (no starter code provided)").strip()[:6000]}
```

Write the script Kojo speaks, in a friendly, clear teaching voice. Return a JSON object ONLY (no prose, no code fences) with EXACTLY these keys:
- "title": short name of the optimal approach, e.g. "Two pointers".
- "breakdown": 2 to 4 short spoken lines reading the problem and breaking it down: what is given, what is asked, the key constraint or insight to notice. Each line 1 to 2 sentences.
- "key_points": 2 to 4 very short on-screen bullets (under 10 words each) summarizing the breakdown.
- "approaches": 2 or 3 objects from brute force to optimal, each {{"name": "...", "time": "O(...)", "space": "O(...)", "verdict": one of "optimal", "works", "too slow", "fails", "idea": "one sentence on how it works", "why": "one sentence on why it works, is too slow, or fails", "say": "1 to 2 spoken sentences Kojo says about it"}}. The last one is the optimal approach with verdict "optimal".
- "code": the complete optimal solution as an array of lines in order, each {{"line": "<one source line, verbatim with its indentation>", "say": "<what this line does and why, 1 short spoken sentence, or \\"\\" for trivial lines>"}}. Joined with newlines the lines must form a runnable `class Solution:` with the SAME method name and parameters as the starter code. No comments inside the code.
- "time_complexity": e.g. "O(n)".
- "space_complexity": e.g. "O(1)".
- "complexity_say": 1 to 2 spoken sentences on why the time and space are what they are.

Spoken lines are read aloud: no Markdown, no code symbols beyond simple names, say "n" not "$n$".
Return only the JSON object."""


def sketch_prompt(title: str, statement: str, approach: str, code: str) -> str:
    return f"""You are Kojo, a coding-interview coach drawing on a whiteboard in a video walkthrough, the way NeetCode sketches a problem before coding it.

PROBLEM: {(title or "this problem").strip()[:300]}
STATEMENT:
{(statement or "").strip()[:6000]}

THE APPROACH YOU ARE ABOUT TO CODE: {approach.strip()[:600]}
```python
{code.strip()[:4000]}
```

Draw how the approach works on a small example, as a short sequence of frames. The board is {CANVAS_W} units wide and {CANVAS_H} units tall, origin top-left, x to the right, y down. Each frame ADDS ink to the board (earlier frames stay visible), so build the picture up step by step. When the next step would need to draw over what is already there, start that frame with "clear": true to wipe the board and redraw the current state cleanly.

Return a JSON object ONLY (no prose, no code fences):
{{"frames": [ {{"say": "1 to 2 spoken sentences explaining this step", "clear": false, "strokes": [ {{"points": [x0, y0, x1, y1, ...], "color": "ink" | "red" | "blue" | "green"}} ], "labels": [ {{"x": 10, "y": 8, "text": "short text", "color": "ink"}} ]}} ]}}

Rules:
- 3 to {MAX_FRAMES} frames. Up to {MAX_STROKES_PER_FRAME} strokes and {MAX_LABELS_PER_FRAME} labels per frame. Up to {MAX_POINTS_PER_STROKE} points per stroke.
- Draw a grid as its row lines and column lines (one stroke per line), not one box per cell.
- Keep a notes column on the right (x from 62 to 98) for variables like count = 1. To UPDATE a value, write the new label at the SAME x, y as the old one: the board erases the old text for you. Put NEW notes on a new line below.
- Mark a visited or current cell with a circle around it (about 12 points, radius 3 to 4), never a tiny scribble.
- Every arrow must start and end at something drawn. No decorative marks: if a stroke does not show part of the idea, leave it out.
- A stroke is one pen movement through its points. Draw boxes as one closed stroke (5 points, back to the start), arrows as a line plus two short head strokes, circles as about 12 points around a center.
- Put numbers and names in labels, not strokes. Keep label text under 16 characters.
- Lay things out neatly: array cells as a row of equal boxes about 8 to 10 units wide, pointers as arrows from below, a tree as circles joined by lines.
- Use "red" or "blue" for what changes in a step (a moving pointer, the current node), "green" for a found answer, "ink" for the structure.
- NEVER write a label on top of an earlier label or draw a stroke through earlier text. Plan the board in rows (for example the input near the top, working state in the middle, the answer near the bottom) and give each new label its own empty spot. Change a value by writing the new one beside it or by clearing the board.
- Keep every coordinate inside the board.
Return only the JSON object."""


def normalize_script(data: dict[str, Any]) -> dict[str, Any]:
    breakdown = [_text(x, SAY_CHARS) for x in (data.get("breakdown") or []) if _text(x, SAY_CHARS)][:MAX_BREAKDOWN]
    key_points = [_text(x, 120) for x in (data.get("key_points") or []) if _text(x, 120)][:MAX_BREAKDOWN]
    approaches = []
    for item in data.get("approaches") or []:
        if not isinstance(item, dict) or not _text(item.get("name"), 80):
            continue
        verdict = _text(item.get("verdict"), 20).lower()
        approaches.append({
            "name": _text(item.get("name"), 80),
            "time": _text(item.get("time"), 40),
            "space": _text(item.get("space"), 40),
            "verdict": verdict if verdict in VERDICTS else "works",
            "idea": _text(item.get("idea"), SAY_CHARS),
            "why": _text(item.get("why"), SAY_CHARS),
            "say": _text(item.get("say"), SAY_CHARS),
        })
    approaches = approaches[:MAX_APPROACHES]
    code = []
    for item in data.get("code") or []:
        if isinstance(item, dict) and isinstance(item.get("line"), str):
            code.append({"line": item["line"].rstrip()[:300], "say": _text(item.get("say"), SAY_CHARS)})
    code = code[:MAX_CODE_LINES]
    # Drop leading/trailing blank lines so the typing animation starts on real code.
    while code and not code[0]["line"].strip():
        code.pop(0)
    while code and not code[-1]["line"].strip():
        code.pop()
    return {
        "title": _text(data.get("title"), 120) or "Optimal approach",
        "breakdown": breakdown,
        "key_points": key_points,
        "approaches": approaches,
        "code": code,
        "time_complexity": _text(data.get("time_complexity"), 40),
        "space_complexity": _text(data.get("space_complexity"), 40),
        "complexity_say": _text(data.get("complexity_say"), SAY_CHARS),
    }


# Layout cleanup. Weaker models stack new text on old text, so after normalizing we
# lay the frames out like a whiteboard: rewriting a spot erases what was there, other
# clashes are nudged to free space, and a frame that cannot fit starts a fresh board.
LABEL_CHAR_W = 2.0
LABEL_H = 4.4
NUDGE_STEP = 5.0

Box = tuple[float, float, float, float]


def _label_box(x: float, y: float, text: str) -> Box:
    # x, y is the text baseline start.
    return (x, y - LABEL_H * 0.82, x + max(1, len(text)) * LABEL_CHAR_W, y + LABEL_H * 0.18)


def _overlap(a: Box, b: Box) -> bool:
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def _place(label: dict[str, Any], taken: list[Box]) -> bool:
    """Move a label to the nearest free spot (down, then up, then right). False if none."""
    x, y, text = label["x"], label["y"], label["text"]
    width = max(1, len(text)) * LABEL_CHAR_W
    tries = [(0.0, 0.0)] + [(0.0, d * NUDGE_STEP) for d in (1, -1, 2, -2)] + [(d * NUDGE_STEP, 0.0) for d in (1, 2, 3)]
    for dx, dy in tries:
        nx = min(max(0.0, x + dx), max(0.0, CANVAS_W - width))
        ny = min(max(LABEL_H, y + dy), CANVAS_H - 0.5)
        box = _label_box(nx, ny, text)
        if not any(_overlap(box, t) for t in taken):
            label["x"], label["y"] = round(nx, 1), round(ny, 1)
            taken.append(box)
            return True
    return False


TINY_MARK = 3.5
MARK_RADIUS = 3.2


def _fix_tiny_marks(strokes: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Weaker models mark a cell with a 2 unit scribble. A tiny shape of 4+ points
    becomes a readable circle around its center; arrow heads (2 points) are kept."""
    import math

    out = []
    for st in strokes:
        pts = st["points"]
        xs, ys = pts[0::2], pts[1::2]
        if len(xs) >= 4 and max(xs) - min(xs) < TINY_MARK and max(ys) - min(ys) < TINY_MARK:
            cx, cy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
            circle: list[float] = []
            for k in range(13):
                a = 2 * math.pi * k / 12
                circle += [round(min(max(cx + MARK_RADIUS * math.cos(a), 0), CANVAS_W), 1),
                           round(min(max(cy + MARK_RADIUS * math.sin(a), 0), CANVAS_H), 1)]
            st = {**st, "points": circle}
        out.append(st)
    return out


def _area(box: Box) -> float:
    return max(0.0, box[2] - box[0]) * max(0.0, box[3] - box[1])


def _shared(a: Box, b: Box) -> float:
    inter = (max(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), min(a[3], b[3]))
    return _area(inter) / max(1e-6, min(_area(a), _area(b)))


def layout_frames(frames: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Whiteboard rules, applied in order:
    - a label written where an older label sits (same spot) ERASES the old one: it
      gets `until` = this frame, and the client fades it out;
    - any other clash nudges the new label to free space;
    - a frame whose labels cannot fit anywhere wipes the board first (`clear`), as
      does a frame where the model asked for it. Idempotent, so cached walkthroughs
      re-run it."""
    live: list[tuple[Box, dict[str, Any]]] = []  # labels on the board since the last clear
    for fi, frame in enumerate(frames):
        frame["strokes"] = _fix_tiny_marks(frame["strokes"])
        for label in frame["labels"]:
            label.pop("until", None)
        if frame.get("clear"):
            live = []
        # Same-spot rewrites erase the old label.
        for label in frame["labels"]:
            box = _label_box(label["x"], label["y"], label["text"])
            for old_box, old in live:
                if "until" not in old and _shared(box, old_box) >= 0.4 and abs(old["y"] - label["y"]) < LABEL_H * 0.6:
                    old["until"] = fi
        live = [(b, l) for b, l in live if "until" not in l]
        boxes = [b for b, _ in live]
        # Strokes may pass over old text (DFS arrows across a grid's digits are the
        # point), so only labels that cannot fit anywhere force a fresh board.
        trial = list(boxes)
        placed = all(_place(dict(label), trial) for label in frame["labels"])
        if live and not placed:
            frame["clear"] = True
            live, boxes = [], []
        for label in frame["labels"]:
            _place(label, boxes)  # keeps its spot when free, else nudges
            live.append((_label_box(label["x"], label["y"], label["text"]), label))
        frame["clear"] = bool(frame.get("clear"))
    if frames:
        frames[0]["clear"] = False  # the board starts empty anyway
    return frames


def relayout(walk: dict[str, Any]) -> dict[str, Any]:
    """Re-run the board cleanup on a cached walkthrough (older ones were saved before it)."""
    frames = walk.get("frames")
    if isinstance(frames, list):
        walk["frames"] = normalize_sketch({"frames": frames})
    return walk


def normalize_sketch(data: dict[str, Any]) -> list[dict[str, Any]]:
    frames = []
    for raw in data.get("frames") or []:
        if not isinstance(raw, dict):
            continue
        strokes = []
        for stroke in (raw.get("strokes") or [])[:MAX_STROKES_PER_FRAME]:
            if not isinstance(stroke, dict) or not isinstance(stroke.get("points"), list):
                continue
            pts = stroke["points"][: MAX_POINTS_PER_STROKE * 2]
            clean: list[float] = []
            for i in range(0, len(pts) - 1, 2):
                x, y = _num(pts[i], CANVAS_W), _num(pts[i + 1], CANVAS_H)
                if x is not None and y is not None:
                    clean += [x, y]
            if len(clean) >= 4:
                color = stroke.get("color")
                strokes.append({"points": clean, "color": color if color in INK_COLORS else "ink"})
        labels = []
        for label in (raw.get("labels") or [])[:MAX_LABELS_PER_FRAME]:
            if not isinstance(label, dict):
                continue
            x, y, text = _num(label.get("x"), CANVAS_W), _num(label.get("y"), CANVAS_H), _text(label.get("text"), 24)
            if x is None or y is None or not text:
                continue
            color = label.get("color")
            labels.append({"x": x, "y": y, "text": text, "color": color if color in INK_COLORS else "ink"})
        say = _text(raw.get("say"), SAY_CHARS)
        if strokes or labels:
            frames.append({"say": say, "clear": raw.get("clear") is True, "strokes": strokes, "labels": labels})
    return layout_frames(frames[:MAX_FRAMES])


def is_usable(script: dict[str, Any]) -> bool:
    """A walkthrough needs a breakdown and code with a Solution class to be worth caching."""
    joined = "\n".join(line["line"] for line in script["code"])
    return bool(script["breakdown"]) and "class Solution" in joined


def code_text(script: dict[str, Any]) -> str:
    return "\n".join(line["line"] for line in script["code"])
